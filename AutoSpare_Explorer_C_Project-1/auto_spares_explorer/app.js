function showNotice(message) {
  appNotice.textContent = message;
  appNotice.classList.add("visible");
  clearTimeout(noticeTimer);
  noticeTimer = setTimeout(() => appNotice.classList.remove("visible"), 3200);
}

try {
  const storedParts = JSON.parse(localStorage.getItem(storageKey) || "[]");
  if (Array.isArray(storedParts) && storedParts.every(part => typeof part === "string")) {
    savedParts = new Set(storedParts);
  }
} catch (error) {
  showNotice("Saved parts are unavailable in this browser session.");
}

function partKey(vehicle, part) {
  return `${vehicle}:${part[1]}`;
}

function getPartPhoto(part) {
  return partPhotos[part[4]] || null;
}

function updateSavedCount() {
  savedCount.textContent = savedParts.size;
}

function updateDetail(vehicle, part) {
  selectedPart = { vehicle, part };
  detailIcon.textContent = part[0];
  detailCategory.textContent = part[2].toUpperCase();
  detailName.textContent = part[1];
  detailDescription.textContent = part[3];
  updatePartShowcase(vehicle, part);
  savePartBtn.disabled = false;
  const isSaved = savedParts.has(partKey(vehicle, part));
  savePartBtn.classList.toggle("is-saved", isSaved);
  savePartBtn.setAttribute("aria-pressed", String(isSaved));
  savePartBtn.innerHTML = `${isSaved ? "★" : "☆"} <span>${isSaved ? "Saved" : "Save part"}</span>`;
  partsGrid.querySelectorAll(".part-card").forEach(card => {
    card.classList.toggle("selected", card.dataset.partKey === partKey(vehicle, part));
    card.setAttribute("aria-pressed", String(card.dataset.partKey === partKey(vehicle, part)));
  });
  partsFloat.querySelectorAll(".float-part").forEach(button => {
    button.classList.toggle("selected", button.dataset.partKey === partKey(vehicle, part));
    button.setAttribute("aria-pressed", String(button.dataset.partKey === partKey(vehicle, part)));
  });
}

function updatePartShowcase(vehicleId, part) {
  const vehicle = vehicles.find(item => item.id === vehicleId);
  const photo = getPartPhoto(part);
  const image = stagePartImage;
  image.classList.remove("is-turning");
  image.onerror = null;
  image.dataset.photoUrl = photo?.url || "";
  if (!photo) {
    image.removeAttribute("src");
    image.alt = "";
    stagePartName.textContent = part[1];
    stagePartKind.textContent = `${vehicle.name} · NO MATCHED REFERENCE PHOTO`;
    stagePartCredit.textContent = "We do not have a verified photo for this component yet.";
    stagePartCredit.removeAttribute("href");
    return;
  }
  image.src = photo.url;
  image.alt = photo.alt;
  image.onerror = () => {
    if (image.dataset.photoUrl !== photo.url) return;
    image.classList.remove("is-turning");
    stagePartKind.textContent = `${vehicle.name} · PHOTO UNAVAILABLE`;
    stagePartCredit.textContent = "The reference image could not be loaded.";
    stagePartCredit.removeAttribute("href");
  };
  stagePartName.textContent = part[1];
  stagePartKind.textContent = `${vehicle.name} · ${part[2].toUpperCase()}`;
  stagePartCredit.textContent = `Photo: ${photo.credit} · Wikimedia Commons`;
  stagePartCredit.href = photo.page;
  requestAnimationFrame(() => image.classList.add("is-turning"));
}

