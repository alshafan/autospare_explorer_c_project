savePartBtn.addEventListener("click", () => {
  if (!selectedPart) return;
  const key = partKey(selectedPart.vehicle, selectedPart.part);
  if (savedParts.has(key)) {
    savedParts.delete(key);
  } else {
    savedParts.add(key);
  }
  try {
    localStorage.setItem(storageKey, JSON.stringify([...savedParts]));
  } catch (error) {
    showNotice("Could not save changes to browser storage. Your shortlist is temporary.");
  }
  updateSavedCount();
  updateDetail(selectedPart.vehicle, selectedPart.part);
  renderParts();
});

