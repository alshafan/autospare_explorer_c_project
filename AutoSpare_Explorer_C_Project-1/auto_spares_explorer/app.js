function renderParts() {
  if (!selectedVehicle) return;
  const term = search.value.trim().toLowerCase();
  const vehicle = vehicles.find(item => item.id === selectedVehicle);
  const filtered = vehicle.inventory.filter(part => {
    const matchesCategory = activeFilter === "all" || part[2] === activeFilter;
    const matchesSearch = part[1].toLowerCase().includes(term) || part[3].toLowerCase().includes(term);
    const matchesSaved = !savedOnly || savedParts.has(partKey(selectedVehicle, part));
    return matchesCategory && matchesSearch && matchesSaved;
  });

  resultsCount.textContent = `${filtered.length} ${filtered.length === 1 ? "component" : "components"}${savedOnly ? " saved" : ""}`;
  partsGrid.replaceChildren();
  if (!filtered.length) {
    const empty = document.createElement("div");
    empty.className = "empty-state";
    const icon = document.createElement("span");
    icon.textContent = savedOnly ? "☆" : "⌕";
    const heading = document.createElement("h3");
    heading.textContent = savedOnly ? "No saved parts here yet." : "No matching parts found.";
    const description = document.createElement("p");
    description.textContent = savedOnly
      ? "Save a component to add it to your personal shortlist."
      : "Try another keyword or category.";
    empty.append(icon, heading, description);
    partsGrid.appendChild(empty);
    return;
  }

  filtered.forEach((part, index) => {
    const card = document.createElement("button");
    card.type = "button";
    card.className = "part-card";
    card.dataset.partKey = partKey(selectedVehicle, part);
    card.style.animationDelay = `${index * 45}ms`;
    card.setAttribute("aria-pressed", String(selectedPart?.part === part));
    const top = document.createElement("span");
    top.className = "part-card-top";
    const icon = document.createElement("span");
    icon.className = "part-icon";
    icon.textContent = part[0];
    const photo = getPartPhoto(part);
    const preview = document.createElement("span");
    preview.className = `part-thumb${photo ? "" : " no-photo"}`;
    if (photo) {
      const thumbnail = document.createElement("img");
      thumbnail.src = photo.url;
      thumbnail.alt = "";
      thumbnail.loading = "lazy";
      thumbnail.onerror = () => {
        preview.textContent = "NO PHOTO";
        preview.setAttribute("aria-label", "Reference photo unavailable");
      };
      preview.appendChild(thumbnail);
    } else {
      preview.textContent = "NO PHOTO";
      preview.setAttribute("aria-label", "No verified component photo");
    }
    const category = document.createElement("span");
    category.className = "part-tag";
    category.textContent = part[2];
    top.append(icon, preview, category);
    const name = document.createElement("span");
    name.className = "part-name";
    name.textContent = part[1];
    const description = document.createElement("span");
    description.className = "part-description";
    description.textContent = part[3];
    const saved = document.createElement("span");
    saved.className = "card-saved";
    saved.textContent = savedParts.has(partKey(selectedVehicle, part)) ? "★ SAVED" : "";
    card.append(top, name, description, saved);
    card.addEventListener("click", () => updateDetail(selectedVehicle, part));
    partsGrid.appendChild(card);
  });
}

